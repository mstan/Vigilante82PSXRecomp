"""Generate the Resident Loading catalog from an owned SLUS-00868 disc.

Writes metadata only (paths, original extents, sizes and SHA-256 hashes over
each file's complete sectors), never asset bytes. Every data file the game's
own loader reads is listed; STR movies and XA speech stay on the CD path, and
SYSTEM.CNF / the boot executable are read by the BIOS, not the game loader.
"""
import argparse
import hashlib
import sys
from pathlib import Path

EXCLUDED_SUFFIXES = ('.STR', '.XA')
EXCLUDED_FILES = {'SYSTEM.CNF', 'SLUS_008.68'}
# The stream loader the adapter replaces: WholeRead 80017F50 through the end of
# Seek, including the sector-ready callback and Wait whose effects it reproduces.
LOADER_LO, LOADER_HI = 0x80017F50, 0x80018708
EXE_BASE, EXE_HEADER = 0x80010000, 0x800


def catalog(disc):
    entries = []
    for name, (lba, size) in sorted(disc.files.items(), key=lambda item: item[1][0]):
        if name.endswith(EXCLUDED_SUFFIXES) or name in EXCLUDED_FILES:
            continue
        padded = (size + 2047) // 2048 * 2048
        raw = disc.reader.read_file_bytes(lba, padded)
        if len(raw) != padded:
            raise ValueError(f'{name}: short read')
        entries.append((name, lba, size, hashlib.sha256(raw).hexdigest()))
    return entries


def loader_contract(disc):
    exe = disc.read('SLUS_008.68')
    text = exe[EXE_HEADER + LOADER_LO - EXE_BASE:EXE_HEADER + LOADER_HI - EXE_BASE]
    return hashlib.sha256(text).hexdigest()


def render(entries, contract):
    total = sum((size + 2047) // 2048 * 2048 for _, _, size, _ in entries)
    lines = ['// Generated by tools/v82_resident_catalog.py from SLUS-00868: original',
             '// extents, sizes and SHA-256 over complete sectors. No disc content.',
             f'// {len(entries)} files, {total} sector bytes.',
             'static const V82ResidentEntry kCatalog[] = {']
    lines += [f'    {{"{name}", {lba}u, {size}u, "{digest}"}},' for name, lba, size, digest in entries]
    lines += ['};',
              f'static constexpr uint32_t kLoaderLo = 0x{LOADER_LO:08X}u, kLoaderHi = 0x{LOADER_HI:08X}u;',
              f'static constexpr const char* kLoaderSha256 = "{contract}";', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--disc', type=Path, required=True, help='SLUS-00868 .cue')
    parser.add_argument('--framework', type=Path,
                        default=Path(__file__).resolve().parents[1] / 'psxrecomp-v4')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='fail when --output differs')
    args = parser.parse_args()
    sys.path.insert(0, str(args.framework / 'tools'))
    from aot_overlay_pipeline import Disc
    disc = Disc(args.disc)
    text = render(catalog(disc), loader_contract(disc))
    if args.check:
        current = args.output.read_text(encoding='utf-8') if args.output.exists() else ''
        if current != text:
            raise SystemExit(f'{args.output} is stale; rerun without --check')
        print('catalog current')
        return
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding='utf-8', newline='\n')
    print(f'catalog written to {args.output}')


if __name__ == '__main__':
    main()
